package ru.iac.inscheck.model;

/**
 * Перечень проверок (Таблица 4 постановки): код, текст и признак фатальности.
 *
 * Фатальная ошибка прекращает обработку (поиск СП не выполняется), ack = 2.
 * Нефатальная ошибка не прекращает обработку: некорректный реквизит считается
 * незаполненным (см. примечания к Таблице 4), СП всё равно выдаётся при наличии.
 */
public enum ErrCode {

    // Раздел 1. Проверка структуры
    STRUCT(2, "Структура файла не соответствует эталону.", true),
    FORMAT(3, "Неверный формат или значность реквизита.", false),
    REQUIRED(4, "Не все обязательные поля заполнены.", true),
    LIMIT(5, "Превышен дневной лимит на количество запросов.", true),

    // Системная (непредвиденная) ошибка — НЕ из Таблицы 4. Инфраструктурный сбой:
    // БД недоступна, нет прав на таблицу, SQL-ошибка и т.п. Пользователю отдаётся
    // обезличенный текст; детали (какой пользователь/БД/таблица) — ТОЛЬКО в лог.
    SYSTEM(500, "Произошла системная ошибка. Повторите операцию позже.", true),

    // Раздел 2. Проверка данных
    // Тексты 100–305 — дословно из Oracle inscheck.getErrText (идут в errtext ответа).
    E100(100, "Дата/период указан неверно", true),
    E101(101, "Недопустимые символы в ФИО пациента", false),
    E102(102, "Пол указан неверно", false),
    E103(103, "Дата рождения указана неверно", false),
    E104(104, "Тип полиса указан неверно", false),
    E105(105, "Номер полиса указан неверно", false),
    E106(106, "Тип документа указан неверно, или документ заполнен не полностью", false),
    E107(107, "СНИЛС указан неверно", false),
    E108(108, "Номер полиса отсутствует в Регистре", false),
    E109(109, "Файл содержит две или более записи с одинаковым идентификатором записи (NREC)", true),
    E110(110, "Тип организации указан неверно", false),
    // Текст изменён намеренно (по решению тестировщика) — отличается от старого сервиса,
    // где было «Код организации указан неверно».
    E111(111, "Код для данного типа организации указан неверно", false),

    // Раздел 3. Проверки соответствия данных Регистру
    E200(200, "СП не найдена", false),
    E201(201, "СП не определена: найдено более одного ЗЛ. Уточните данные ЗЛ.", false),
    E202(202, "ФИО не соответствует актуальной записи Регистра", false),
    E203(203, "Пол не соответствует актуальной записи Регистра", false),
    E204(204, "ДР не соответствует актуальной записи Регистра", false),
    E205(205, "Номер полиса не соответствует актуальной записи Регистра", false),
    E206(206, "Документ не соответствует актуальной записи Регистра", false),
    E207(207, "СНИЛС не соответствует актуальной записи Регистра", false),
    E208(208, "Место рождения не соответствует актуальной записи Регистра", false),

    // Раздел 4. Проверки особенностей найденной СП
    E300(300, "Актуальная СП не определена: СП принадлежит умершему", false),
    E301(301, "Актуальная СП не определена: застрахованный выбыл за пределы Свердловской области", false),
    E302(302, "Актуальная СП не определена: мотивированный отказ", false),
    E303(303, "Актуальная СП не определена: полис найден после даты поиска", false),
    E304(304, "Актуальная СП не определена: полис закрыт в РС ЕРЗ", false),
    E305(305, "Отсутствует актуальное на дату/период поиска прикрепление ЗЛ", false);

    private final int code;
    private final String text;
    private final boolean fatal;

    ErrCode(int code, String text, boolean fatal) {
        this.code = code;
        this.text = text;
        this.fatal = fatal;
    }

    public int getCode() { return code; }
    public String getText() { return text; }
    public boolean isFatal() { return fatal; }
}
